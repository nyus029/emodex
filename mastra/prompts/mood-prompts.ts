/**
 * 心象文・文章生成に使うプロンプトテンプレートを集約したモジュール。
 */

/**
 * 心象文（mood sentence）生成プロンプト。
 * 選んだ単語のニュアンスを反映し、自然な1文を生成する。
 */
export const MOOD_SENTENCE_PROMPT = (wordList: string[]) =>
  `以下の単語はユーザーが「今の気持ち」として選んだものです。
これらの単語が表す感情や心理状態を汲み取り、ユーザーの心象を自然な日本語の1文で表現してください。

単語: ${wordList.join(', ')}

要件:
- 単語の意味やニュアンスを反映してください（単語そのものを文中に含める必要はありません）
- ユーザーの内面が伝わる、共感できる文章にしてください
- 1文だけ生成し、句点で終わってください
- 文章のみを出力してください`;

/**
 * 汎用的な文章生成プロンプト。
 * 単語を含む意味の通った1文を生成する（従来の sentence-from-words 用）。
 */
export const SENTENCE_FROM_WORDS_PROMPT = (wordList: string[]) =>
  `以下の単語を使って、意味の通った自然な日本語の文章を1文だけ作成してください。
単語: ${wordList.join(', ')}

要件:
- できるだけ多くの単語を含めてください
- 自然で意味のある文章にしてください
- 1文だけ生成してください
- 句点で終わってください

文章のみを出力してください。`;
